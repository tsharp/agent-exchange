function execute(config, input2) {
  return new Promise((resolveResponse, reject) => {
    const child = spawn(config.command, config.args, {
      shell: false,
      stdio: ["pipe", "pipe", "pipe"],
      windowsHide: true
    });
    let stdout = "";
    let outputBytes = 0;
    let settled = false;
    const finish = (action) => {
      if (settled) return;
      settled = true;
      clearTimeout(timer);
      action();
    };
    const timer = setTimeout(() => {
      child.kill();
      finish(() => reject(new Error(`controller timed out after ${config.timeoutMs} ms`)));
    }, config.timeoutMs);
    child.stdout.setEncoding("utf8");
    child.stdout.on("data", (chunk) => {
      outputBytes += Buffer.byteLength(chunk);
      if (outputBytes > MAX_OUTPUT_BYTES) {
        child.kill();
        finish(() => reject(new Error("controller output exceeded 64 KiB")));
        return;
      }
      stdout += chunk;
    });
    child.stderr.resume();
    child.on("error", (error) => finish(() => reject(error)));
    child.on("close", (code) => finish(() => {
      if (code !== 0) reject(new Error(`controller exited with status ${code ?? "unknown"}`));
      else {
        try {
          resolveResponse(parseResponse(stdout));
        } catch (error) {
          reject(error);
        }
      }
    }));
    child.stdin.end(input2);
  });
}
